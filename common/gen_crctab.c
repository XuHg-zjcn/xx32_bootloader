#include <stdint.h>
#include <stdio.h>

/* @berif 生成CRC表格(目前只能生成Modbus专用)，输出C语言格式数组
 * @param nbit: 同时处理的比特数
 * @retval none
 */
void generate_table_nb(uint32_t nbit)
{
  printf("//generated by `%s` program\n", __FILE__);
  printf("const uint16_t table_mbcrc_%db[] = {\n", nbit);
  for(int i=0;i<(1<<nbit);i++){
    uint16_t crc = i;
    for(int j=0;j<nbit;j++){
      if(crc & 0x0001) {
	crc = (crc>>1) ^ 0xa001;
      }else{
	crc >>= 1;
      }
      crc &= 0xffff;
    }
    printf("0x%04x", crc);
    if(i != (1<<nbit)-1){
      printf(", ");
    }
    if(i%8 == 7){
      printf("\n");
    }
  }
  printf("};\n");
}

int main()
{
  generate_table_nb(8); //生成8位表，占用2*256=512Byte空间
  printf("\n");
  generate_table_nb(4); //生成4位表，占用2*16=32Byte空间
}
